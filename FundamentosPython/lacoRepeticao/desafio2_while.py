'''2) Crie um programa que continue pedindo, repetidas vezes, para que o 
usuário insira um número qualquer. O programa deve se encerrar somente quando 
o usuário inserir o valor 0(zero). '''

num = 1;

while num != 0 : 
    num = int(input("Digite um número até que a sequência se encerre aqui: "))
    print(num)

print("Você digitou 0 e o programa acabou!");






    

